#!/usr/bin/env node
// data-inventory.mjs - write docs/Compliance/Data-Inventory.md from
// models/lib/personalDataInventory.js (docs/Compliance/README.md, WP-3).
//
// The module is the inventory; the Markdown is only a view of it, so it is
// never edited by hand: change the module and run this.
// tests/personalDataInventory.test.cjs fails when the committed file is not
// exactly what this writes.
//
//   node releases/compliance/data-inventory.mjs            # write the doc
//   node releases/compliance/data-inventory.mjs --check    # exit 1 if out of date
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const DOC = 'docs/Compliance/Data-Inventory.md';
const require = createRequire(import.meta.url);
const inventory = require(path.join(ROOT, 'models/lib/personalDataInventory.js'));

// One table cell: no line breaks, and a | would end the cell.
const cell = text => String(text == null ? '-' : text).replace(/\s+/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').trim() || '-';
const code = text => (text ? `\`${text}\`` : '-');

function retentionOf(entry) {
  const { env, default: dflt } = entry.retention;
  return env ? `${dflt} (${env})` : dflt;
}

function whereOf(entry) {
  const parts = [`defined: ${code(entry.definedIn)}`];
  if (entry.retention.where) parts.push(`retention: ${code(entry.retention.where)}`);
  parts.push(`erasure: ${entry.erasureWhere ? code(entry.erasureWhere) : 'nothing yet'}`);
  return parts.join('; ');
}

function categoriesOf(entry) {
  return entry.categories
    .map(c => (inventory.SPECIAL_CATEGORIES.includes(c) ? `**${c}**` : c))
    .join(', ');
}

export function dataInventoryMarkdown(mod = inventory) {
  const all = mod.INVENTORY;
  const personal = mod.personalDataEntries();
  const health = mod.entriesWithCategory('health').map(e => code(e.collection));
  const financial = mod.entriesWithCategory('financial').map(e => code(e.collection));
  const gaps = mod.erasureGaps().map(code);
  const lines = [
    '# Personal-data inventory',
    '',
    '<!-- Generated by releases/compliance/data-inventory.mjs from',
    '     models/lib/personalDataInventory.js. Do not edit by hand. -->',
    '',
    'Which MongoDB collection holds which personal data, why, for how long, and',
    'what happens to it when a person is erased: the inventory of',
    '[Compliance](README.md) rows 2.1 and 2.2 (work package WP-3). It is the',
    'starting point of a record of processing activities ([GDPR] Art. 30(1)) that',
    'the operator of an instance completes: the legal basis column is a hint, the',
    'operator decides it, and the recipients depend on what the instance has',
    'enabled (mail server, file storage, webhooks, integrations).',
    '',
    `- **${all.length} collections**, ${personal.length} of them with personal data.`,
    `- **Health data** ([GDPR] Art. 9 special category): ${health.join(', ') || 'none'}.`,
    `- **Financial data**: ${financial.join(', ') || 'none'}.`,
    `- **Not erased yet** (erasure should delete or anonymise, nothing does it today;`,
    `  the work list of WP-4): ${gaps.length} collections - ${gaps.join(', ') || 'none'}.`,
    '',
    'Categories: identity (who a person is), contact (e-mail and other addresses),',
    'network (IP addresses, devices), usage (what a person did and when), content',
    '(what a person wrote or uploaded), **health**, **financial**, auth (credentials,',
    'tokens, keys), none (no personal data). Erasure: delete, anonymize,',
    'keep-pseudonymous (kept, linked only by an id) or n/a.',
    '',
    '| Collection | Categories | Subject field | Purpose | Legal basis hint | Retention | Erasure | Where | Notes |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const e of all) {
    lines.push('| ' + [
      code(e.collection), categoriesOf(e), e.subjectField ? code(e.subjectField) : '-',
      cell(e.purpose), cell(e.legalBasisHint), cell(retentionOf(e)), cell(e.erasure),
      whereOf(e), cell(e.notes),
    ].join(' | ') + ' |');
  }
  lines.push('', '[GDPR]: https://eur-lex.europa.eu/eli/reg/2016/679/oj "Regulation (EU) 2016/679"', '');
  return lines.join('\n');
}

function main() {
  const want = dataInventoryMarkdown();
  const file = path.join(ROOT, DOC);
  const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error(`${DOC} is not what models/lib/personalDataInventory.js gives: run node releases/compliance/data-inventory.mjs`);
      process.exit(1);
    }
    return;
  }
  if (have !== want) fs.writeFileSync(file, want);
  console.log(`${DOC}: ${inventory.INVENTORY.length} collections.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
