// Whether the collection holds personal data at all.
function holdsPersonalData(entry) {
  return !(entry.categories.length === 1 && entry.categories[0] === 'none');
}

function personalDataEntries(inventory = INVENTORY) {
  return inventory.filter(holdsPersonalData);
}

function entriesWithCategory(category, inventory = INVENTORY) {
  return inventory.filter(entry => entry.categories.includes(category));
}

// Collections whose erasure should delete or anonymise but that nothing
// erases today: the work list of WP-4.
function erasureGaps(inventory = INVENTORY) {
  return inventory
    .filter(entry => (entry.erasure === 'delete' || entry.erasure === 'anonymize') && !entry.erasureWhere)
    .map(entry => entry.collection);
}

function entryFor(collection, inventory = INVENTORY) {
  return inventory.find(entry => entry.collection === collection) || null;
}

