'use strict';

// Personal-data inventory: every MongoDB collection WeKan defines, what
// personal data it holds, why, for how long, and what happens to it when a
// person is erased (docs/Compliance/README.md rows 2.1 and 2.2, work package
// WP-3; [GDPR] Art. 30(1), [LGPD] Art. 37, [PIPL] Art. 51).
//
// It is the ONE list the later work packages are driven from - erasure
// (WP-4), the personal-data export (WP-5) and the privacy notice and Admin
// Panel / Settings / Privacy pages (WP-6) - so a collection added without an
// entry here is a collection none of them know about.
// tests/personalDataInventory.test.cjs scans the tree for every
// `new Mongo.Collection('x')` and Meteor-Files `collectionName: 'x'` and
// fails on one that is missing, on an entry whose collection no longer
// exists, and on a new erasure gap. docs/Compliance/Data-Inventory.md is
// generated from it by releases/compliance/data-inventory.mjs.
//
// Fields of an entry:
//   collection      the MongoDB collection name.
//   definedIn       the file that defines it; `definedBy` is the text that
//                   proves it there for a collection that has no
//                   `new Mongo.Collection` line (Meteor.users, GridFS buckets).
//   categories      subset of CATEGORIES; ['none'] alone = no personal data.
//                   'health' and 'financial' are SPECIAL_CATEGORIES: health is
//                   a special category under [GDPR] Art. 9 (workload absences
//                   of type "sick"); financial data needs the same care.
//   subjectField    the field(s) linking a row to a person, or null.
//   purpose         one sentence.
//   legalBasisHint  a HINT for the controller (the operator of the instance),
//                   not a decision: the operator decides its legal basis.
//   retention       { env: the environment variable or Admin Panel setting
//                   that limits it, or null; default: how long it is kept;
//                   where: the file that enforces it, or null }.
//   erasure         what erasing a person should do to their rows:
//                   'delete', 'anonymize', 'keep-pseudonymous' (kept, linked
//                   only by an id, e.g. authored history kept by #1289) or
//                   'n/a'.
//   erasureWhere    the file that ACTUALLY does it today on user deletion or
//                   anonymisation, or null when nothing does (the WP-4 gap).
//   notes           what a reader needs to know, honestly.
//
// Pure data and helpers, no Meteor, CommonJS - like models/lib/userDeletionCleanup.js.

