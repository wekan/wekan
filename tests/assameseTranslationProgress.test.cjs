assert.match(assamese['advanced-filter-description'], /== != <= >= && \|\| \( \).*F1 == \/Tes\.\*\/i/);
assert.match(assamese['import-board-instruction-issues'], /__sourceName__.*__endpoint__/);
assert.match(assamese['email-invite-register-text'], /__user__,\n\n__inviter__.*\n\n.*\n__url__\n\n.*__icode__\n\n/s);
