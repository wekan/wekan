assert.match(assamese['act-addChecklistItem'], /__card__/);
assert.match(assamese['act-addChecklistItem'], /__list__/);
assert.match(assamese['act-addChecklistItem'], /__swimlane__/);
assert.match(assamese['act-addChecklistItem'], /__board__/);
